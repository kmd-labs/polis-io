#!/usr/bin/env node
/**
 * Rasterizes Natural Earth 1:10m country polygons into the pixel grid used by the game.
 *
 * Every cell is classified as:
 *   '.' sea, 'g' Greek land (playable), 'f' foreign land (rendered, never playable)
 *
 * The result is written run-length encoded to src/app/game/data/greece-map.ts.
 * Usage: node scripts/build-map.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(__dirname, '../src/app/game/data/greece-map.ts');
const SRC =
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_admin_0_countries.geojson';

// Map window (degrees). Cells are square on the ground at the window's mid latitude.
const LON0 = 19.2;
const LON1 = 28.4;
const LAT0 = 34.75;
const LAT1 = 41.85;
const CELL_LAT = 0.034;
const MID_LAT = (LAT0 + LAT1) / 2;
const CELL_LON = CELL_LAT / Math.cos((MID_LAT * Math.PI) / 180);

const cols = Math.round((LON1 - LON0) / CELL_LON);
const rows = Math.round((LAT1 - LAT0) / CELL_LAT);

console.log(`Downloading ${SRC} ...`);
const res = await fetch(SRC);
if (!res.ok) throw new Error(`HTTP ${res.status}`);
const geo = await res.json();

const grid = new Array(cols * rows).fill('.');

/** Returns polygon rings (arrays of [lon, lat]) of a feature that touch the map window. */
function ringsOf(feature) {
  const g = feature.geometry;
  if (!g) return [];
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : [];
  const rings = [];
  for (const poly of polys) {
    for (const ring of poly) {
      let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
      for (const [x, y] of ring) {
        if (x < minX) minX = x;
        if (x > maxX) maxX = x;
        if (y < minY) minY = y;
        if (y > maxY) maxY = y;
      }
      if (maxX < LON0 || minX > LON1 || maxY < LAT0 || minY > LAT1) continue;
      rings.push(ring);
    }
  }
  return rings;
}

/** Even-odd scanline fill of all rings, sampling at cell centres. */
function fill(rings, value) {
  for (let r = 0; r < rows; r++) {
    const lat = LAT1 - (r + 0.5) * CELL_LAT;
    const xs = [];
    for (const ring of rings) {
      for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
        const [xi, yi] = ring[i];
        const [xj, yj] = ring[j];
        if ((yi > lat) !== (yj > lat)) {
          xs.push(xi + ((lat - yi) / (yj - yi)) * (xj - xi));
        }
      }
    }
    xs.sort((a, b) => a - b);
    for (let k = 0; k + 1 < xs.length; k += 2) {
      const c0 = Math.max(0, Math.ceil((xs[k] - LON0) / CELL_LON - 0.5));
      const c1 = Math.min(cols - 1, Math.floor((xs[k + 1] - LON0) / CELL_LON - 0.5));
      for (let c = c0; c <= c1; c++) grid[r * cols + c] = value;
    }
  }
}

let greek = 0;
for (const f of geo.features) {
  const iso = f.properties.ADM0_A3 ?? f.properties.ISO_A3;
  const rings = ringsOf(f);
  if (!rings.length) continue;
  fill(rings, iso === 'GRC' ? 'g' : 'f');
  if (iso === 'GRC') greek++;
}
if (!greek) throw new Error('Greece not found in source data');

// Run-length encode: "<count><char>" pairs, row-major.
let rle = '';
let run = 1;
for (let i = 1; i <= grid.length; i++) {
  if (i < grid.length && grid[i] === grid[i - 1]) {
    run++;
  } else {
    rle += `${run}${grid[i - 1]}`;
    run = 1;
  }
}

const greekCells = grid.filter(v => v === 'g').length;
const out = `// AUTO-GENERATED by scripts/build-map.mjs from Natural Earth 1:10m (public domain). Do not edit.
// ${cols}×${rows} cells, ${greekCells} Greek land cells.

export const GREECE_MAP = {
  cols: ${cols},
  rows: ${rows},
  lon0: ${LON0},
  lat1: ${LAT1},
  cellLon: ${CELL_LON.toFixed(6)},
  cellLat: ${CELL_LAT},
  /** Run-length encoded cells: '.' sea, 'g' Greek land, 'f' foreign land. */
  rle: '${rle}'
} as const;
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out, 'utf8');
console.log(`✅ Wrote ${path.relative(process.cwd(), OUT)} (${cols}×${rows}, ${greekCells} Greek cells, ${rle.length} chars)`);
